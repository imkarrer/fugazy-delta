"""Racelogic VBO files: read and write.

VBO is a text format: bracketed sections, a `[column names]` line, then
whitespace-separated rows under `[data]`. Its conventions differ from ours
and are converted at this boundary only:

- latitude and longitude are in *minutes*, and longitude is positive WEST
- time is UTC `HHMMSS.SS` with no date; the date comes from the
  `File created on dd/mm/yyyy` line, and rows roll over at midnight
- velocity is km/h

Columns are matched by name, case-insensitively, so files from different
exporters (Racelogic, RaceBox, RaceChrono) load as long as they carry the
core channels. Unknown columns are ignored.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from .model import Telemetry

_ALIASES = {
    "time": {"time"},
    "lat": {"lat", "latitude"},
    "lon": {"long", "lon", "longitude"},
    "speed": {"velocity", "speed", "velocity_kmh"},
    "heading": {"heading"},
    "alt": {"height", "altitude", "alt"},
    "accel_long": {"longacc", "long_acc", "longaccel", "longitudinal_acc", "accel_long"},
    "accel_lat": {"latacc", "lat_acc", "lataccel", "lateral_acc", "accel_lat"},
    "accel_vert": {"vertacc", "vert_acc", "accel_vert"},
}

_CREATED = re.compile(r"File created on (\d{1,2})/(\d{1,2})/(\d{4})")


def _hms_to_seconds(value: str) -> float:
    v = float(value)
    hh = int(v // 10000)
    mm = int((v % 10000) // 100)
    ss = v - hh * 10000 - mm * 100
    return hh * 3600 + mm * 60 + ss


def read_vbo(path: str | Path, date: datetime | None = None, source: str = "vbo") -> Telemetry:
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    section = None
    columns: list[str] = []
    rows: list[list[str]] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if date is None and (m := _CREATED.search(line)):
            day, month, year = map(int, m.groups())
            date = datetime(year, month, day, tzinfo=timezone.utc)
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1].strip().lower()
            continue
        if section == "column names":
            columns = [c.lower() for c in line.split()]
        elif section == "data":
            rows.append(line.split())
    if not columns:
        raise ValueError(f"{path}: no [column names] section")
    if not rows:
        raise ValueError(f"{path}: no data rows")
    if date is None:
        raise ValueError(f"{path}: no 'File created on' date; pass date=")

    index: dict[str, int] = {}
    for field, names in _ALIASES.items():
        for i, col in enumerate(columns):
            if col in names:
                index[field] = i
                break
    for required in ("time", "lat", "lon"):
        if required not in index:
            raise ValueError(f"{path}: missing {required!r} column (have {columns})")

    width = len(columns)
    rows = [r for r in rows if len(r) == width]

    def col(field):
        if field not in index:
            return None
        return np.array([float(r[index[field]]) for r in rows])

    seconds = np.array([_hms_to_seconds(r[index["time"]]) for r in rows])
    rollover = np.concatenate([[0], np.cumsum(np.diff(seconds) < -43200)]) * 86400.0
    time = date.timestamp() + seconds + rollover

    speed = col("speed")
    return Telemetry(
        source=source,
        time=time,
        lat=col("lat") / 60.0,
        lon=-col("lon") / 60.0,
        alt=col("alt"),
        speed=None if speed is None else speed / 3.6,
        heading=col("heading"),
        accel_long=col("accel_long"),
        accel_lat=col("accel_lat"),
        accel_vert=col("accel_vert"),
    )


def write_vbo(telemetry: Telemetry, path: str | Path, satellites: int = 12, comment: str = "") -> None:
    """Write `telemetry` as a VBO file with the core channels plus g-forces."""
    created = datetime.fromtimestamp(telemetry.time[0], tz=timezone.utc)
    midnight = created.replace(hour=0, minute=0, second=0, microsecond=0).timestamp()
    lines = [
        f"File created on {created:%d/%m/%Y} @ {created:%H:%M:%S}",
        "",
        "[header]",
        "satellites",
        "time",
        "latitude",
        "longitude",
        "velocity kmh",
        "heading",
        "height",
        "longacc",
        "latacc",
        "",
        "[comments]",
        comment or "Generated by fugazy-delta",
        "",
        "[column names]",
        "sats time lat long velocity heading height longacc latacc",
        "",
        "[data]",
    ]
    t = telemetry
    for i in range(len(t)):
        secs = (t.time[i] - midnight) % 86400.0
        hh, rem = divmod(secs, 3600)
        mm, ss = divmod(rem, 60)
        # round seconds to the file's precision before carrying, so 59.9999
        # never prints as "60.000"
        ss = round(ss, 3)
        if ss >= 60.0:
            ss -= 60.0
            mm += 1
            if mm >= 60:
                mm -= 60
                hh = (hh + 1) % 24
        hms = f"{int(hh):02d}{int(mm):02d}{ss:06.3f}"
        lines.append(
            f"{satellites:03d} {hms} "
            f"{t.lat[i] * 60.0:+012.6f} {-t.lon[i] * 60.0:+012.6f} "
            f"{_num(t.speed[i] * 3.6, '07.3f')} {_num(t.heading[i], '06.2f')} "
            f"{_num(t.alt[i], '+09.2f')} {_num(t.accel_long[i], '+06.3f')} {_num(t.accel_lat[i], '+06.3f')}"
        )
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def _num(value: float, fmt: str) -> str:
    return format(0.0 if np.isnan(value) else value, fmt)
