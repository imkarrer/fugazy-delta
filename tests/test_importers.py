def test_binary_signatures_are_tried_before_text():
    kinds = [i.binary for i in importers()]
    assert kinds == sorted(kinds, reverse=True)


def test_every_kind_has_one_importer():
    seen = [i.kind for i in importers()]
    assert len(seen) == len(set(seen))


def test_identifies_by_content_whatever_the_name(racebox, tmp_path):
    path = tmp_path / "session.mp4"  # wrong extension on purpose
    write_vbo(racebox, path, comment="Generated by RaceBox")
    assert identify(path) is Kind.VBO


def test_bom_is_stripped_before_text_sniffing(racebox, tmp_path):
    plain = tmp_path / "a.vbo"
    write_vbo(racebox, plain)
    bom = tmp_path / "b.vbo"
    bom.write_bytes(codecs.BOM_UTF8 + plain.read_bytes())
    assert Head.of(bom).text.startswith("File created on")
    assert identify(bom) is Kind.VBO
    np.testing.assert_allclose(read(bom).telemetry.lat, read(plain).telemetry.lat)


def test_unknown_files_get_advice(tmp_path):
    path = tmp_path / "notes.txt"
    path.write_text("cone 14 is tight\n")
    with pytest.raises(UnsupportedFile, match="notes.txt: not a file format we can read") as exc:
        identify(path)
    assert "RaceChrono" in str(exc.value) and "GoPro" in str(exc.value)


def test_binary_junk_is_unsupported(tmp_path):
    path = tmp_path / "x.bin"
    path.write_bytes(bytes(range(256)) * 10)
    with pytest.raises(UnsupportedFile):
        identify(path)


@pytest.mark.parametrize("comment,device,profile", [
    ("Generated by RaceBox", "RaceBox", PRECISE),
    ("(c) Racelogic", "Racelogic VBOX", PRECISE),
    ("Exported by RaceChrono Pro", "RaceChrono", COARSE),
    ("", "VBO logger", COARSE),
])
def test_vbo_device_decides_the_accuracy_profile(racebox, tmp_path, comment, device, profile):
    path = tmp_path / "s.vbo"
    write_vbo(racebox, path, comment=comment or " ")
    rec = read(path)
    assert (rec.kind, rec.device, rec.profile) == (Kind.VBO, device, profile)
    assert rec.utc and not rec.camera


def test_session_names_the_logger_and_quotes_its_profile(racebox, tmp_path):
    path = tmp_path / "phone.vbo"
    write_vbo(racebox, path, comment="Exported by RaceChrono Pro")
    session = Session.from_files([path])
    assert session.setup is Setup.RACEBOX_ONLY
    assert session.setup_label == "RaceChrono"
    assert session.method == COARSE
    features = session.features("autocross")
    assert features[Feature.LAP_TIMES].support is Support.APPROXIMATE
    assert "RaceChrono GPS is a phone or unknown receiver" in features[Feature.LAP_TIMES].reason
    assert accuracy.error("autocross", COARSE, "lap").summary() in features[Feature.LAP_TIMES].reason
    assert features[Feature.VIDEO_OVERLAY].support is Support.UNAVAILABLE


def test_session_times_from_the_best_logger(racebox, tmp_path):
    phone = tmp_path / "phone.vbo"
    write_vbo(racebox, phone, comment="Exported by RaceChrono Pro")
    rb = tmp_path / "rb.vbo"
    write_vbo(racebox, rb, comment="Generated by RaceBox")
    session = Session.from_files([phone, rb])
    assert session.primary.device == "RaceBox"
    assert session.method == PRECISE
    assert any("RaceChrono file was read but not used" in w for w in session.warnings)


# ---------- shared conversions ----------

@pytest.mark.parametrize("unit,factor", [("m/s", 1.0), ("km/h", 3.6), ("mph", 2.2369363), ("knots", 1.9438445)])
def test_speed_unit_inferred_from_positions(racebox, unit, factor):
    got, ratio = infer_speed_unit(racebox.time, racebox.lat, racebox.lon, racebox.speed * factor)
    assert got == unit
    assert ratio == pytest.approx(factor, rel=0.05)


def test_speed_unit_not_guessed_when_stationary(racebox):
    n = len(racebox)
    unit, _ = infer_speed_unit(racebox.time, np.full(n, racebox.lat[0]), np.full(n, racebox.lon[0]), racebox.speed)
    assert unit is None


@pytest.mark.parametrize("text,unit", [("Km/h", "km/h"), ("MPH", "mph"), ("kph", "km/h"), ("m/s", "m/s"), ("furlongs", None)])
def test_speed_unit_names(text, unit):
    assert speed_unit(text) == unit


def test_accel_conventions():
    long, lat = accel_to_model([0.5], [0.2], long_forward=False, lat_left=False)
    assert long[0] == -0.5 and lat[0] == -0.2


def test_keep_fixes_drops_repeats_and_backwards_time():
    t = np.array([0.0, 0.1, 0.1, 0.05, 0.2])
    assert keep_fixes(t).tolist() == [True, True, False, False, True]


def test_epoch_rows_pick_the_row_nearest_each_fix():
    t = 1000.0 + np.array([0.0, 0.004, 0.011, 0.497, 0.999, 1.003, 1.5])
    assert epoch_rows(t, 1.0).tolist() == [True, False, False, False, True, False, False]
